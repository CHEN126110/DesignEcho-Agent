/**
 * 通用视觉设计原理（知识底座）—— 给 Agent 打「科班设计师」的设计基本功。
 *
 * 分工：
 * - main-image-framework 讲「主图要传达什么卖点 / 内容策略」（讲什么）。
 * - 本模块讲「怎么把画面做得有构图、有层次、有品质」（怎么做好看），且通用于任何品类/版式。
 * 二者互补：策略决定说什么，原理决定怎么呈现。Agent 之前只有前者，所以产出停在排版。
 *
 * accessibility/image-quality/anti-patterns/decision-priority 四个模块是后补的「可检测底线」层：
 * 前六个模块偏审美判断（构图美不美、色彩搭不搭），这四个模块给的是可核对的客观门槛
 * （WCAG 对比度/间距数值、图像技术缺陷、可枚举反模式、优先级排序规则），二者互补而不重复。
 * WCAG 数值来自 WCAG 2.2 成功标准（1.4.3/1.4.11/1.4.12/2.5.8），非本项目实测，按官方标准直接采信。
 *
 * 双重用途：
 * - 设计依据：Agent 在出视觉方案时按这些原理逐维度思考，用设计语言表达决策。
 * - 评审基准：critic / 设计质量验收据此打分，而不是只看「图层建了没、居中了没」。
 *
 * 红线（与项目一致）：知识只作上下文与评审依据，不直接授权写入，
 * 也不允许把本模块内容硬编码进 Agent 运行时分支。
 */


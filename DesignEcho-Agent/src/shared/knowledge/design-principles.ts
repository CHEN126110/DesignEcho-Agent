/**
 * 按焦点取视觉设计原理；不传或传 'all' 返回全量（带小标题）。
 */
export function buildDesignPrinciplesSummary(focus?: DesignPrincipleFocus | 'all'): string {
    if (focus && focus !== 'all' && SECTIONS[focus]) {
        const section = SECTIONS[focus];
        return `## ${section.title}\n${section.content}`;
    }
    return (Object.keys(SECTIONS) as DesignPrincipleFocus[])
        .map((key) => `## ${SECTIONS[key].title}\n${SECTIONS[key].content}`)
        .join('\n\n');
}


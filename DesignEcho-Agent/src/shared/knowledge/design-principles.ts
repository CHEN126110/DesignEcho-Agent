    '主体占比：主体要足够大才有识别度与冲击力（电商主图主体常占画面 40%~60%）；主体太小 = 画面空洞无力。',
    '尺寸参照：主体该多大不靠感觉——有同类优秀参考（项目内成品、用户给的参考、设计师 PSD）时先测参考（measureReferenceComposition 读出主体占比/重心/留白，照测量值参照）；无参考时按上一条档位起步。数值是起点不是教条，放完必观察复核。',
    '留白：留白是为突出主体、给画面呼吸的主动设计，不是「没填满」。留白要克制、有目的，集中在主体周围制造焦点。',
    '视线动线：用元素排布引导视线（F 型 / Z 型 / 中心放射），让视线自然落到主体与核心信息，再到次要信息。',
    '平衡与张力：画面要平衡（对称或非对称平衡），但适度打破对称能制造张力与活力，避免呆板对称。',
    '对齐与网格：元素按网格、边缘、中线对齐，建立秩序感。对齐混乱 = 廉价感，是新手最容易暴露的破绽。',
    '判断点：有没有明确主体焦点？主体够不够大够突出？留白是有目的还是空洞？视线动线顺不顺？画面平衡吗？元素对齐吗？'
